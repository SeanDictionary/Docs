from Crypto.Util.number import *
 

flag = b"flag{it_will_show_you_how_solve_HNP}"
seed = bytes_to_long(flag)
 
class LCG:
    def __init__(self, bits:int, seed:int):
        self.bits = bits
        self.m = getPrime(self.bits)
        self.a = getPrime(self.bits // 2)
        self.cur = (self.a * seed) % self.m
 
    def extract(self):
        ret = self.cur
        b = getPrime(self.bits // 4)
        self.cur = ( self.a * self.cur + b ) % self.m
        return ret
 
lcg = LCG(512, seed)
c = [lcg.extract() for _ in range(5)]
 
print(f'c = {c}')
print(f'm = {lcg.m}')
 
